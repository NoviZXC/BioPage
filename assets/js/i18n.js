(function () {
  var SUPPORTED = ['es', 'en', 'fr', 'ar'];
  var S = window.I18N_STRINGS || {};
  var orig = {};

  function nodes() { return document.querySelectorAll('[data-i18n]'); }

  function captureOriginals() {
    nodes().forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (orig[k] === undefined) orig[k] = el.innerHTML;
    });
  }

  function apply(lang) {
    if (SUPPORTED.indexOf(lang) === -1) lang = 'en';
    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
    nodes().forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      var val = (lang === 'es') ? orig[k] : (S[k] && S[k][lang]);
      if (val !== undefined && val !== null) el.innerHTML = val;
    });
    try { localStorage.setItem('lang', lang); } catch (e) {}
    document.querySelectorAll('.lang-switch [data-lang]').forEach(function (b) {
      b.classList.toggle('on', b.getAttribute('data-lang') === lang);
    });
  }

  function detect() {
    var q = (new URLSearchParams(window.location.search)).get('lang');
    if (q && SUPPORTED.indexOf(q) !== -1) return q;
    var saved = null;
    try { saved = localStorage.getItem('lang'); } catch (e) {}
    if (saved && SUPPORTED.indexOf(saved) !== -1) return saved;
    var nav = (navigator.language || navigator.userLanguage || 'en').slice(0, 2).toLowerCase();
    return (SUPPORTED.indexOf(nav) !== -1) ? nav : 'en';
  }

  function init() {
    captureOriginals();
    document.querySelectorAll('.lang-switch [data-lang]').forEach(function (b) {
      b.addEventListener('click', function (e) {
        e.preventDefault();
        apply(b.getAttribute('data-lang'));
      });
    });
    apply(detect());
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
